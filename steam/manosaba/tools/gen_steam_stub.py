#!/usr/bin/env python3
"""Generate an offline steam_api stub for iOS from the entry names the game references.

Every flat-API function returns 0 (NULL / false / k_EResultOK-free "nothing happened").
Init entry points report failure so Steamworks.NET's SteamManager logs and carries on
instead of quitting (RestartAppIfNecessary -> false keeps the app running).
"""
from __future__ import annotations

import argparse
import logging
import re
import subprocess
import sys

log = logging.getLogger("gen_steam_stub")

NAME_RE = re.compile(r"^(SteamAPI|SteamInternal|SteamGameServer|SteamClient|SteamEncryptedAppTicket)[A-Za-z0-9_]*$")

SPECIAL = {
    # ESteamAPIInitResult: 1 == k_ESteamAPIInitResult_FailedGeneric; message buffer is SteamErrMsg[1024]
    "SteamInternal_SteamAPI_Init":
        "int SteamInternal_SteamAPI_Init(const char *v, char *err) {\n"
        "    (void)v; stub_log(\"SteamInternal_SteamAPI_Init -> FailedGeneric\");\n"
        "    if (err) { strncpy(err, \"Steam is unavailable in the iOS port (stub).\", 1023); err[1023] = 0; }\n"
        "    return 1;\n}\n",
    "SteamInternal_GameServer_Init_V2":
        "int SteamInternal_GameServer_Init_V2(unsigned a, unsigned short b, unsigned short c, int d, const char *e, const char *f, char *err) {\n"
        "    (void)a; (void)b; (void)c; (void)d; (void)e; (void)f;\n"
        "    if (err) { strncpy(err, \"stub\", 1023); err[1023] = 0; }\n"
        "    return 1;\n}\n",
    "SteamAPI_RestartAppIfNecessary":
        "bool SteamAPI_RestartAppIfNecessary(unsigned app) { stub_log(\"SteamAPI_RestartAppIfNecessary(%u) -> false\", app); return false; }\n",
}


def entry_names(game_dylib: str) -> list[str]:
    out = subprocess.run(["strings", "-a", game_dylib], check=True, capture_output=True, text=True).stdout
    return sorted({s for s in out.splitlines() if NAME_RE.match(s)})


def render(names: list[str]) -> str:
    body = [
        "// Generated by tools/gen_steam_stub.py -- do not edit.",
        "#include <stdbool.h>",
        "#include <stdarg.h>",
        "#include <stdio.h>",
        "#include <string.h>",
        "#include <os/log.h>",
        "",
        "static void stub_log(const char *fmt, ...) {",
        "    char buf[256]; va_list ap; va_start(ap, fmt); vsnprintf(buf, sizeof buf, fmt, ap); va_end(ap);",
        "    os_log(OS_LOG_DEFAULT, \"[steam_stub] %{public}s\", buf);",
        "}",
        "",
    ]
    for n in names:
        if n in SPECIAL:
            body.append(SPECIAL[n])
        else:
            body.append(f"void *{n}(void) {{ return 0; }}")
    return "\n".join(body) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("game_dylib", help="GameAssembly (arm64) to scan for entry names")
    ap.add_argument("out_c", help="output C file")
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    names = entry_names(args.game_dylib)
    missing = [k for k in SPECIAL if k not in names]
    if missing:
        log.warning("special entries not referenced by the game: %s", missing)
    with open(args.out_c, "w") as f:
        f.write(render(names))
    log.info("wrote %s with %d entry points", args.out_c, len(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
