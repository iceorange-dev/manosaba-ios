#!/usr/bin/env python3
"""Generate RegisterAllStrippedInternalCalls() covering every icall in the iOS player lib.

Unity's iOS build only registers the internal calls the (stripped) shell project uses.
The transplanted macOS GameAssembly needs the full set the macOS player exposes, so we
call every `Register_*()` function that libiPhone-lib.a defines.
"""
from __future__ import annotations

import argparse
import logging
import re
import subprocess
import sys

log = logging.getLogger("gen_icall_registration")

# nm prints C++ symbols with an extra leading underscore: __Z<len>Register_<name>v == void Register_<name>()
SYM_RE = re.compile(r"^__Z(\d+)(Register_(?:UnityEngine|Unity|UnityEngineInternal)_[A-Za-z0-9_]+)v$")


def defined_register_functions(lib: str) -> list[str]:
    out = subprocess.run(["nm", "-gU", lib], check=True, capture_output=True, text=True).stdout
    names: set[str] = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        m = SYM_RE.match(parts[2])
        if m and int(m.group(1)) == len(m.group(2)):
            names.add(m.group(2))
    return sorted(names)


def render(names: list[str]) -> str:
    decls = "\n".join(f"void {n}();" for n in names)
    calls = "\n".join(f"\t{n}();" for n in names)
    return (
        "// Generated by tools/gen_icall_registration.py -- do not edit.\n"
        f"// Registers all {len(names)} internal calls defined by libiPhone-lib.a.\n"
        f"{decls}\n\n"
        "void RegisterAllStrippedInternalCalls()\n{\n"
        f"{calls}\n"
        "}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("lib", help="libiPhone-lib.a")
    ap.add_argument("out", help="output .cpp")
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    names = defined_register_functions(args.lib)
    if len(names) < 1000:
        log.error("only %d Register_ functions found; wrong lib?", len(names))
        return 2
    with open(args.out, "w") as f:
        f.write(render(names))
    log.info("wrote %s with %d registrations", args.out, len(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
